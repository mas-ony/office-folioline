/**
 * What makes the editor a full-page app (shared by the React and Vue apps): the document or live
 * session in the address, the example documents, stored settings and autosave, the window title
 * and the page's language, opening files dropped on the window or passed by the installed app, and
 * the page API on `window`.
 */
import { DOCX_MIME, type DocxEditorRef, type Example, type FoliolineOptions, type FoliolineUI, initialLocale, installPageApi, loadMessages, makeTranslate } from '@folioline/core';

/** Settings are kept in localStorage, and unsaved work in IndexedDB, under this name. */
const KEY = 'folioline';

/** Example documents shipped with the app (generated by scripts/make-fixtures.mjs). */
export const EXAMPLES: Example[] = [
  { id: 'sample', url: './examples/sample.docx' },
  { id: 'agreement', url: './examples/agreement.docx' },
  { id: 'template', url: './examples/template.docx' },
  { id: 'long', url: './examples/long-report.docx' },
  { id: 'tables', url: './examples/tables-columns.docx' },
  { id: 'international', url: './examples/international.docx' },
  { id: 'formatting', url: './examples/formatting.docx' },
];

/**
 * Options from the address: `?room=` joins a live session, `?src=` and `?example=` open a document
 * and `?new` starts with a blank one. Otherwise the sample opens, and unsaved work from the last
 * visit is offered for recovery.
 */
export async function shellOptions(): Promise<FoliolineOptions> {
  const params = new URLSearchParams(location.search);
  const room = params.get('room');
  const src = params.get('src');
  const example = EXAMPLES.find((x) => x.id === params.get('example'));
  const start = !room && !src && !example && !params.has('new');
  // The sample is named in the reader's language.
  const locale = initialLocale(KEY);
  const t = makeTranslate(locale, start ? await loadMessages(locale).catch(() => ({})) : {});
  return {
    examples: EXAMPLES,
    storageKey: KEY,
    autosave: KEY,
    offerRecovery: start,
    globalShortcuts: true,
    room: room ?? undefined,
    document: src
      ? { url: src, name: decodeURIComponent(src.split('/').pop() || 'Document.docx') }
      : example
        ? { url: example.url }
        : start
          ? { url: './examples/sample.docx', name: `${t('app.sample')}.docx` }
          : undefined,
  };
}

interface LaunchQueue {
  setConsumer(fn: (p: { files: FileSystemFileHandle[] }) => void): void;
}

/** Connect the ready editor to the page; returns the function that disconnects it. */
export function connectShell(ref: DocxEditorRef, ui: FoliolineUI): () => void {
  const editor = ref.getEditor();
  const title = () => {
    document.title = `${editor.dirty ? '• ' : ''}${editor.fileName.replace(/\.docx$/i, '')} – ${ui.getState().t('app.name')}`;
  };
  // The page follows the interface: its background, and its language and direction (the title too).
  let shown = '';
  const page = () => {
    const { locale, rtl, scheme } = ui.getState();
    const html = document.documentElement;
    html.classList.toggle('is-dark', scheme === 'dark');
    if (locale === shown) return;
    shown = locale;
    html.lang = locale;
    html.dir = rtl ? 'rtl' : 'ltr';
    title();
  };
  page();
  title();
  const offs = [
    editor.on('change', title),
    editor.on('load', title),
    ui.subscribe(page),
    installPageApi(ref),
  ];

  // Open .docx files dropped anywhere on the window (pictures go to the document).
  const isDocx = (f: File) => /\.(docx|dotx|doc)$/i.test(f.name) || f.type === DOCX_MIME;
  const over = (e: DragEvent) => {
    if (Array.from(e.dataTransfer?.items ?? []).some((i) => i.kind === 'file' && i.type !== '' && !i.type.startsWith('image/'))) e.preventDefault();
  };
  const drop = (e: DragEvent) => {
    const file = Array.from(e.dataTransfer?.files ?? []).find(isDocx);
    if (!file) return;
    e.preventDefault();
    e.stopPropagation();
    if (ui.confirmDiscard()) void ui.open(file);
  };
  const before = (e: BeforeUnloadEvent) => {
    if (editor.dirty) {
      e.preventDefault();
      e.returnValue = '';
    }
  };
  const keys = (e: KeyboardEvent) => {
    if ((e.ctrlKey || e.metaKey) && !e.shiftKey && !e.altKey && e.key.toLowerCase() === 'o') {
      e.preventDefault();
      ui.files.open();
    }
  };
  window.addEventListener('dragover', over);
  window.addEventListener('drop', drop, true);
  window.addEventListener('beforeunload', before);
  window.addEventListener('keydown', keys);

  // Files opened through the installed app (PWA file handling).
  (window as unknown as { launchQueue?: LaunchQueue }).launchQueue?.setConsumer(async (p) => {
    const handle = p.files?.[0];
    if (handle) void ui.open(await handle.getFile());
  });

  return () => {
    for (const off of offs) off();
    window.removeEventListener('dragover', over);
    window.removeEventListener('drop', drop, true);
    window.removeEventListener('beforeunload', before);
    window.removeEventListener('keydown', keys);
  };
}

/** The installed app works offline (production builds only). */
export function registerServiceWorker() {
  if ('serviceWorker' in navigator) {
    window.addEventListener('load', () => {
      navigator.serviceWorker.register('./sw.js').catch(() => undefined);
    });
  }
}
