const BADGES: Record<Badge, { kind: string; text: string }> = {
  fileWord: { kind: 'word', text: 'W' },
  filePdf: { kind: 'pdf', text: 'PDF' },
  fileMd: { kind: 'md', text: 'MD' },
};

/** A menu icon by its name; the file types of Export are badges. */
export function Icon({ name, size = 16 }: { name: MenuIcon; size?: number }) {
  if (name in BADGES) {
    const b = BADGES[name as Badge];
    return <span className={cx('fl-filetype', `is-${b.kind}`)}>{b.text}</span>;
  }
  const C = ICONS[name as Exclude<MenuIcon, Badge>];
  return <C size={size} />;
}
